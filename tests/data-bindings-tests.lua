local json, b64, plist = require('json'), require('base64'), require('plist')
local value = assert(json.decode('{"a":[1,true,null,"xin chào"],"b":[]}'))
assert(value.a[3] == json.null and value.a[4] == 'xin chào')
local again = assert(json.decode(assert(json.encode(value))))
assert(again.a[2] == true and again.a[3] == json.null)
assert(json.encode(json.array()) == '[]' and json.encode({}) == '{}')
assert(json.encode(json.null) == 'null' and json.decode('null') == json.null)
assert(json.decode(json.encode('a\0b')) == 'a\0b')
local cycle = {}; cycle.self = cycle
assert(json.encode(cycle) == nil and json.encode({[2]='sparse'}) == nil)
assert(json.encode(0/0) == nil and json.decode('invalid') == nil)
local nested = {}; local cursor = nested
for i=1,70 do cursor.a={};cursor=cursor.a end
assert(json.encode(nested) == nil)
assert(b64.encode('a\0b') == 'YQBi' and b64.decode('YQBi') == 'a\0b')
assert(b64.decode('!invalid!') == nil)
assert(md5('abc') == '900150983cd24fb0d6963f7d28e17f72')
local xml = assert(plist.dump({name='test',flag=true,list={1,2}}))
local decoded = assert(plist.load(xml)); assert(decoded.flag == true and decoded.list[2] == 2)
assert(plist.load('bplist00') == nil and plist.dump(cycle) == nil)
local path = os.tmpname()
assert(plist.write(path, {value='roundtrip'})); assert(plist.read(path).value=='roundtrip')
assert(plist.write(path..'\0suffix', {value='invalid'}) == nil)
assert(plist.read(path).value=='roundtrip'); os.remove(path)
print('Data binding roundtrip, binary, null and failure tests passed')
local lfs = require('lfs'); local dir = os.tmpname(); os.remove(dir)
assert(lfs.mkdir(dir)); assert(lfs.attributes(dir,'mode')=='directory')
local entries={}; for name in lfs.dir(dir) do entries[name]=true end
assert(entries['.'] and entries['..'])
assert(lfs.currentdir() and lfs.attributes(dir,'permissions'):len()==9)
assert(lfs.rmdir(dir)); assert(lfs.attributes(dir)==nil and lfs.dir(dir)==nil)
assert(require('md5').sumhexa('abc')==md5('abc'))
print('Filesystem module iterator and failure tests passed')
